"""Builds bgmt64.cu: the boundary-free seed sweep of bgmt.cu with 64-BIT seeds, for the generators a program seeds from a millisecond clock:

    py3   CPython random.seed(int): MT19937 init_by_array(32-bit words of |n|, least significant first): one word below 2^32, two words above
    ruby  Random.new(int): the same seeding, rand(29) = low 5 bits with rejection, rand = res53 float
    java  new Random(long): the 48-bit scramble of the whole seed; maps nextInt(29), then (int)(nextDouble() * 29) or, with JALT=1, abs(nextInt()) % 29

The text of bgmt.cu is the validated source: this script changes it by exact-snippet substitution (every snippet must occur exactly the stated number of times,
so a change to bgmt.cu makes the build fail instead of silently diverging). Below 2^32 the semantics are those of bgmt.cu (the key values are identical; Java
keeps the sign-extension of a 32-bit int seed there), which tests/test_bgmt64.py checks. The candidate record keeps the low 32 bits of the seed; bg64.py restores
the high bits from the chunk base.

    python work/phpmt/make_bgmt64.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))

HEADER = """// CUDA seed sweep with a BOUNDARY-FREE score and 64-BIT SEEDS (work/phpmt/bg64.py, generated by make_bgmt64.py from bgmt.cu: do not edit).
// For the generators of programs that seed from a millisecond clock (prng-time): py3 / ruby (MT19937 init_by_array with two 32-bit words above 2^32) and java
// (the 48-bit scramble of a long). bg64.py prepends the #defines:  GEN (3 py3, 6 java, 9 ruby)   NW (windows)   DUMP (0 none, 1 every score, 3 both key maps)
//   JALT (java only: 1 = second map abs(nextInt()) % 29 instead of (int)(nextDouble() * 29))
#if GEN != 3 && GEN != 6 && GEN != 9
#error "bgmt64.cu covers py3 (3), java (6) and ruby (9)"
#endif
#ifndef JALT
#define JALT 0
#endif
"""

# (old, new, count)
EDITS = [
    ("__device__ void mt_state(u32 *s, const u32 seed) {\n",
     "__device__ void mt_state(u32 *s, const u64 seed64) {\n    const u32 seed = (u32)seed64, seedhi = (u32)(seed64 >> 32);\n    const int klen = seedhi ? 2 : 1;   // CPython / Ruby: the 32-bit words of the seed, no leading zero word\n", 1),
    ("    int i = 1;\n    for (int k = MT_N; k > 0; k--) {\n        s[i] = (s[i] ^ ((s[i - 1] ^ (s[i - 1] >> 30)) * 1664525u)) + seed;\n        i++;\n"
     "        if (i >= MT_N) { s[0] = s[MT_N - 1]; i = 1; }\n    }\n",
     "    int i = 1, j = 0;\n    for (int k = MT_N; k > 0; k--) {\n        s[i] = (s[i] ^ ((s[i - 1] ^ (s[i - 1] >> 30)) * 1664525u)) + (j == 0 ? seed : seedhi) + (u32)j;\n        i++;\n        j++;\n"
     "        if (i >= MT_N) { s[0] = s[MT_N - 1]; i = 1; }\n        if (j >= klen) j = 0;\n    }\n", 1),
    ("__device__ void gen_keys(const u32 seed, u8 keys[2][K]) {\n",
     "// a 32-bit seed is a Java int (sign-extended), a larger one a long\n#define JSEED(s) ((s) >> 32 ? (u64)(s) : (u64)(long long)(int)(u32)(s))\n"
     "__device__ void gen_keys(const u64 seed64, u8 keys[2][K]) {\n    const u32 seed = (u32)seed64;\n", 1),
    ("    mt_state(s, seed);\n", "    mt_state(s, seed64);\n", 1),
    ("(u64)(long long)(int)seed ^ JMUL", "JSEED(seed64) ^ JMUL", 2),
    ("    for (int i = 0; i < K; i++) {\n        const u64 hi = jnext(st, 26);\n        const u64 lo = jnext(st, 27);\n"
     "        keys[1][i] = (u8)(((double)((hi << 27) + lo) * (1.0 / 9007199254740992.0)) * 29.0);\n    }\n",
     "#if JALT\n    for (int i = 0; i < K; i++) {                                          // abs(nextInt()) % 29 (as prngx: wrapping abs, unsigned %)\n"
     "        const u32 ur = jnext(st, 32);                                      // the bits of the int nextInt(); abs() on them: no signed overflow\n"
     "        keys[1][i] = (u8)(((ur & 0x80000000u) ? 0u - ur : ur) % 29u);\n    }\n#else\n"
     "    for (int i = 0; i < K; i++) {\n        const u64 hi = jnext(st, 26);\n        const u64 lo = jnext(st, 27);\n"
     "        keys[1][i] = (u8)(((double)((hi << 27) + lo) * (1.0 / 9007199254740992.0)) * 29.0);\n    }\n#endif\n", 1),
    ("        const u32 seed = (u32)(seed0 + g);\n", "        const u64 seed64 = seed0 + g;\n        const u32 seed = (u32)seed64;\n", 1),
    ("        gen_keys(seed, keys);\n", "        gen_keys(seed64, keys);\n", 1),
]


def build():
    src = open(os.path.join(HERE, "bgmt.cu"), encoding="utf-8").read()
    for old, new, n in EDITS:
        assert src.count(old) == n, f"bgmt.cu changed: snippet occurs {src.count(old)} times, expected {n}:\n{old}"
        src = src.replace(old, new)
    return HEADER + src


if __name__ == "__main__":
    with open(os.path.join(HERE, "bgmt64.cu"), "w", encoding="utf-8", newline="\n") as f:
        f.write(build())
    print("wrote bgmt64.cu")
