"""Builds bgmt.cu: the generator section of phpmt.cu (copied verbatim, so the key maps are exactly the validated ones) followed by a
boundary-free decoder and kernel. Run it again after changing the decoder text below or the generators of phpmt.cu;
work/tests/test_bgmt.py fails if the generator sections of the two files differ.

    python work/phpmt/make_bgmt.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
MARKER = "// ------------------------------------------------------------------ decoder"

HEADER = """// CUDA seed sweep with a BOUNDARY-FREE score (work/phpmt/bg.py, generated by make_bgmt.py): the generators and key maps are those of
// phpmt.cu (the text from the typedefs up to the decoder marker is identical; tests/test_bgmt.py checks that), but the score of a decoded
// window is the log-likelihood ratio of its plaintext under an English rune-bigram table (data/bigram.txt), not a count of dictionary words
// between the transcription's word separators. Word separators that are independent of the plaintext words (LP2's word lengths show no serial
// structure, results/analysis/wordlen_adjacency.txt) make the dictionary score blind to a true key; this one does not use them. The skip /
// coin beam of decode_fast is kept; states are pruned at every rune (merge on the key pointer, keep the 16 best).
// bg.py prepends the #defines:  GEN (0..9 as in phpmt.cu)   NW (windows)   DUMP (0 none, 1 every score, 3 both key maps)
"""

DECODER = r"""// ------------------------------------------------------------------ boundary-free decoder

__device__ __forceinline__ int subk(int c, int k, int sign) {
    int v = sign > 0 ? c - k : c + k;
    return v < 0 ? v + MOD : (v >= MOD ? v - MOD : v);
}
__device__ __forceinline__ int addk(int t, int k, int sign) {
    int v = sign > 0 ? t + k : t - k;
    return v < 0 ? v + MOD : (v >= MOD ? v - MOD : v);
}

#define NSYM 29
#define BGROW 128                   // runes per window row (up to 128; K = 160 key values)
#define START 29                      // row of the bigram table for the first rune: unigram log-odds

struct BS {
    int score;
    u16 j;
    u8 last;
};

// tbl[a * 29 + b] = round(10 * ln(29 * P(b | a))) for a < 29, row 29 = unigram. meta = {previous rune, runes, abort_at, abort_thr}: give up when
// the best path is below abort_thr after abort_at runes (a true key is far above it)
__device__ int bg_decode(const u8 *__restrict__ runes, const int *__restrict__ meta, const u8 *key, const int sign, const bool atb,
                         const int model, const short *__restrict__ tbl) {
    const int wprev = meta[0], wn = meta[1], abort_at = meta[2], abort_thr = meta[3];
    BS states[16];
    BS next[48];
    int ns = 1;
    states[0].j = 0;
    states[0].last = START;
    states[0].score = 0;
    for (int i = 0; i < wn; i++) {
        const int c = runes[i];
        const int prev = i == 0 ? wprev : (int)runes[i - 1];
        int nn = 0;
        for (int si = 0; si < ns; si++) {
            const BS s = states[si];
            const int j = s.j;
            if (j + 3 >= K) continue;
#define BPUSH(TT, NJ)                                                                                        \
    {                                                                                                        \
        if (nn < 48) {                                                                                       \
            const int t_ = (TT);                                                                             \
            const int p_ = atb ? 28 - t_ : t_;                                                               \
            next[nn].j = (u16)(NJ);                                                                          \
            next[nn].last = (u8)p_;                                                                          \
            next[nn].score = s.score + (int)tbl[s.last * NSYM + p_];                                         \
            nn++;                                                                                            \
        }                                                                                                    \
    }
            const int k0 = key[j];
            if (model == 0) {
                BPUSH(subk(c, k0, sign), j + 1);
                if (prev >= 0) {
                    const int t1 = subk(c, key[j + 1], sign);
                    if (addk(t1, k0, sign) == prev) BPUSH(t1, j + 2);
                    const int t2 = subk(c, key[j + 2], sign);
                    if (addk(t2, k0, sign) == prev && addk(t2, key[j + 1], sign) == prev) BPUSH(t2, j + 3);
                }
            } else {
                if (prev >= 0 && c == prev) BPUSH(subk(c, k0, sign), j + 2)
                else BPUSH(subk(c, k0, sign), j + 1);
                if (prev >= 0) {
                    const int t = subk(c, key[j + 2], sign);
                    if (addk(t, k0, sign) == prev) BPUSH(t, j + 3);
                }
            }
        }
        if (nn == 0) return -100000;
        ns = 0;
        for (int q = 0; q < nn; q++) {                      // merge equal key pointers, keep the 16 best
            const BS s = next[q];
            bool found = false;
            for (int r = 0; r < ns; r++) {
                if (states[r].j == s.j) {
                    if (s.score > states[r].score) states[r] = s;
                    found = true;
                    break;
                }
            }
            if (!found) {
                if (ns < 16) {
                    states[ns++] = s;
                } else {
                    int wi = 0, ws = states[0].score;
                    for (int r = 1; r < 16; r++)
                        if (states[r].score < ws) { ws = states[r].score; wi = r; }
                    if (s.score > ws) states[wi] = s;
                }
            }
        }
        if (i + 1 == abort_at) {
            int best = states[0].score;
            for (int r = 1; r < ns; r++) best = states[r].score > best ? states[r].score : best;
            if (best < abort_thr) return best;
        }
    }
    int best = states[0].score;
    for (int r = 1; r < ns; r++) best = states[r].score > best ? states[r].score : best;
    return best;
}

extern "C" __global__ void __launch_bounds__(128)
bg_kernel(const u8 *__restrict__ wrunes, const int *__restrict__ wmeta, const short *__restrict__ tbl, const u64 seed0,
          const u64 nseeds, const int thr, u64 *ghist, u32 *cand, u32 *ccount, const u32 ccap, int *dump) {
    __shared__ u32 sh[HB];
    for (int b = threadIdx.x; b < HB; b += blockDim.x) sh[b] = 0;
    __syncthreads();
    const u64 g = (u64)blockIdx.x * blockDim.x + threadIdx.x;
    if (g < nseeds) {
        const u32 seed = (u32)(seed0 + g);
        u8 keys[2][K];
#if GEN <= 2
        u32 raw[K];
        gen_raw(seed, raw);
        for (int i = 0; i < K; i++) {
            keys[0][i] = key0(raw[i]);
            keys[1][i] = (u8)(raw[i] % 29u);
        }
#else
        gen_keys(seed, keys);
#endif
#if DUMP == 3
        for (int m = 0; m < 2; m++)
            for (int i = 0; i < K; i++) dump[(g * 2 + m) * K + i] = keys[m][i];
#else
        for (int wi = 0; wi < NW; wi++) {
            for (int v = 0; v < 16; v++) {
                const bool atb = v & 1;
                const int sign = ((v >> 1) & 1) == 0 ? 1 : -1;
                const int map = (v >> 2) & 1;
                const int model = (v >> 3) & 1;
                const int s = bg_decode(wrunes + wi * BGROW, wmeta + 4 * wi, keys[map], sign, atb, model, tbl);
#if DUMP == 1
                dump[(g * NW + wi) * 16 + v] = s;
#endif
                int b = (s + 400) / 20;
                b = b < 0 ? 0 : (b > HB - 1 ? HB - 1 : b);
                atomicAdd(&sh[b], 1u);
                if (s >= thr) {
                    const u32 q = atomicAdd(ccount, 1u);
                    if (q < ccap) {
                        cand[2 * q] = seed;
                        cand[2 * q + 1] = ((u32)(s + 2048) << 16) | ((u32)wi << 8) | (u32)v;
                    }
                }
            }
        }
#endif
    }
    __syncthreads();
    for (int b = threadIdx.x; b < HB; b += blockDim.x)
        if (sh[b]) atomicAdd(&ghist[b], (u64)sh[b]);
}
"""


BGMARKER = "// ------------------------------------------------------------------ boundary-free decoder"


def generator_section(text):
    """the shared part: from the first typedef to the decoder marker (of phpmt.cu or of bgmt.cu)"""
    i = text.index("typedef unsigned char u8")
    return text[i:text.index(MARKER if MARKER in text else BGMARKER)]


def build():
    src = open(os.path.join(HERE, "phpmt.cu"), encoding="utf-8").read()
    return HEADER + generator_section(src) + DECODER


if __name__ == "__main__":
    with open(os.path.join(HERE, "bgmt.cu"), "w", encoding="utf-8", newline="\n") as f:
        f.write(build())
    print("wrote bgmt.cu")
