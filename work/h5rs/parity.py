"""parity.py - the mandatory parity gate for work/h5rs (writes parity.txt).

Compares the Rust engine (engines scalar / fastscalar / fast) against the verified Python
reference (h5slice_nb.beam_coincidence_nats_numba for the init, h5slice.decode(fast_init=True)
for the full decode) on:

  * 24 grid cells: offsets {1234, 1000, 1500, 777} x L {7, 8, 12} x models {0, 1}, each with
    init at abort 0 and abort 120 (48 init checks) and full decode at abort 0 and abort 120
    (48 decode checks);
  * the truth cell (1234, 8, model 0) no-abort: IoC >= 1.6, wcol == DIVINITY, 8 skips;
  * 4 random null windows x random streams (abort 120/0.9): init + decode parity, 4/4 aborts.

Gates (per cell): init pointer list EXACT, skip count EXACT, score within 1e-9 nats, decode
IoC within 1e-12 (bit-exact in practice), wcol EXACT, abort decisions EXACT. The Rust totient
is cross-checked against h5slice.totient(4000). Throughput (single-thread and 8-thread) and
the 880M-decode projection are measured at the end and appended to parity.txt.
"""
import math
import os
import random
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
WORK = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(WORK, "h5slice"))
sys.path.insert(0, WORK)

import numpy as np

import h5slice as H
import h5slice_nb as N
import sim

OUT = os.path.join(HERE, "parity.txt")
CELLS = os.path.join(HERE, "cells.txt")
EXPECTED = os.path.join(HERE, "expected.txt")

ABORT_AT = 120
MARGIN = 0.9
BEAM = 24
MAX_EM = 5
BEAM_A = 12

logf = H.english_logf()
uni = H.uni_mean_logf()
plain = sim.english_runes()[3000:3300]
tvals = H.totient(4000)
TRUTH_OFF = 1234
c_truth = H.plant(plain, tvals, TRUTH_OFF, H.DIVINITY, 0, keep=0.19, litf=False, b=0, seed=42)


def abort_ll(L):
    return ABORT_AT * (uni + MARGIN) + L * math.log(29)


def skips(ptrs):
    return sum(ptrs[i] - ptrs[i - 1] - 1 for i in range(1, len(ptrs))) if len(ptrs) > 1 else 0


lines = []


def log(s=""):
    print(s, flush=True)
    lines.append(s)


def write_out():
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def main():
    t_start = time.time()
    log(f"# parity.txt - h5rs vs h5slice_nb parity gate")
    log(f"# started {time.strftime('%Y-%m-%d %H:%M:%S')}; machine: 16 logical procs; "
        f"Python {sys.version.split()[0]}, numpy {np.__version__}")
    log(f"# reference: h5slice_nb init + h5slice.decode(fast_init=True), beam_a {BEAM_A}, "
        f"beam {BEAM}, max_em {MAX_EM}, abort ({ABORT_AT}, {MARGIN})")
    log(f"# plant: Self-Reliance 3000:3300, totient + DIVINITY, offset {TRUTH_OFF}, model 0, "
        f"keep 0.19, seed 42")
    log()

    # ---- 0. constants: regenerate src/logf.rs and verify it matches the repo file ----
    log("== 0. embedded constants (src/logf.rs) ==")
    vals = ",\n".join(f"    {v!r}" for v in logf.tolist())
    src = (
        "// Generated by gen_consts.py - DO NOT EDIT. Bit-exact Python values:\n"
        "//   logf = H.english_logf()            (Self-Reliance via work/sim.py, add-0.5, np.log)\n"
        "//   uni  = float(np.sum(logf)) / 29    (the unigram-null level)\n"
        "//   ln29 = math.log(29); ln028 = math.log(0.028)\n"
        "pub const LOGF: [f64; 29] = [\n"
        f"{vals},\n"
        "];\n"
        f"pub const UNI: f64 = {float(np.sum(logf)) / 29!r};\n"
        f"pub const LN29: f64 = {math.log(29)!r};\n"
        f"pub const LN028: f64 = {math.log(0.028)!r};\n"
    )
    logf_path = os.path.join(HERE, "src", "logf.rs")
    with open(logf_path, "r", encoding="utf-8") as f:
        existing = f.read()
    if existing != src:
        log(f"  FAIL: src/logf.rs drifted from the Python constants; regenerating")
        with open(logf_path, "w", encoding="utf-8", newline="\n") as f:
            f.write(src)
    else:
        log(f"  ok: src/logf.rs matches H.english_logf() bit-exactly "
            f"(uni {float(np.sum(logf)) / 29!r}, ln29 {math.log(29)!r}, ln028 {math.log(0.028)!r})")
    log()

    # ---- 1. build the cells ----
    cells = []          # (id, off, L, model, stream_kind, stream_vals, tasks, runes)
    expected = []       # list of "<id> <task> ..." lines
    fails = 0
    checks = 0

    def add_expected(entry):
        expected.append(entry)

    # grid: 24 cells
    for off in (1234, 1000, 1500, 777):
        for L in (7, 8, 12):
            for model in (0, 1):
                cid = f"g{off}_{L}_m{model}"
                cells.append((cid, off, L, model, "tot", None,
                              ["init0", "init1", "dec0", "dec1"], c_truth))
                ts = tvals[off:off + 300 + 107]
                for abort_at, ll in ((0, 0.0), (ABORT_AT, abort_ll(L))):
                    r = N.beam_coincidence_nats_numba(c_truth, -1, ts, L, False, BEAM_A,
                                                      logf, abort_at, ll)
                    task = "init0" if abort_at == 0 else "init1"
                    if r is None:
                        add_expected(f"{cid} {task} abort")
                    else:
                        ps, ss = r
                        add_expected(f"{cid} {task} ok ptrs={','.join(map(str, ps))} "
                                     f"score={ss!r} skips={skips(ps)}")
                for abort_at in (0, ABORT_AT):
                    a = H.decode(c_truth, -1, tvals, off, L, model, litf=False, beam=BEAM,
                                 max_em=MAX_EM, logf=logf, abort_at=abort_at,
                                 abort_margin=MARGIN if abort_at else 0.0, out_path=True,
                                 fast_init=True)
                    task = "dec0" if abort_at == 0 else "dec1"
                    if a[1] is None:
                        add_expected(f"{cid} {task} abort")
                    else:
                        info = a[1]
                        add_expected(f"{cid} {task} ok ioc={a[0]!r} "
                                     f"wcol={','.join(map(str, info['wcol']))} "
                                     f"skips={skips(info['ptrs'])}")

    # 4 random nulls (verify_nb phase 4 style, k = 0..3)
    rng = random.Random(7)
    for k in range(4):
        ws = H.random_stream(3400, 100 + k)
        wc = [rng.randrange(29) for _ in range(300)]
        off = rng.randrange(1800)
        cid = f"null{k}"
        ts = ws[off:off + 300 + 107]
        cells.append((cid, off, 8, 0, "vals", ts, ["init1", "dec1"], wc))
        r = N.beam_coincidence_nats_numba(wc, -1, ts, 8, False, BEAM_A, logf, ABORT_AT,
                                          abort_ll(8))
        if r is None:
            add_expected(f"{cid} init1 abort")
        else:
            ps, ss = r
            add_expected(f"{cid} init1 ok ptrs={','.join(map(str, ps))} score={ss!r} "
                         f"skips={skips(ps)}")
        a = H.decode(wc, -1, ws, off, 8, 0, litf=False, beam=BEAM, max_em=MAX_EM, logf=logf,
                     abort_at=ABORT_AT, abort_margin=MARGIN, out_path=True, fast_init=True)
        if a[1] is None:
            add_expected(f"{cid} dec1 abort")
        else:
            info = a[1]
            add_expected(f"{cid} dec1 ok ioc={a[0]!r} wcol={','.join(map(str, info['wcol']))} "
                         f"skips={skips(info['ptrs'])}")

    # ---- 2. reference sanity: the truth cell must be the verified plant ----
    log("== reference sanity (the Python side must reproduce the verified truth) ==")
    a = H.decode(c_truth, -1, tvals, TRUTH_OFF, 8, 0, litf=False, beam=BEAM, max_em=MAX_EM,
                 logf=logf, abort_at=0, abort_margin=0.0, out_path=True, fast_init=True)
    info = a[1]
    sk = skips(info["ptrs"])
    log(f"  truth no-abort: IoC {a[0]:.4f} wcol {info['wcol']} skips {sk}")
    if not (a[0] >= 1.6 and info["wcol"] == H.DIVINITY and sk == 8):
        fails += 1
        log("  FAIL: the Python reference does not reproduce the truth cell - investigate "
            "h5slice before trusting this gate")
    else:
        log("  ok: IoC >= 1.6, wcol == DIVINITY, 8 skips")
    py_null_aborts = 0
    for ln in expected:
        if ln.startswith("null") and ln.split()[1] == "init1" and ln.split()[2] == "abort":
            py_null_aborts += 1
    log(f"  null reference: {py_null_aborts}/4 init aborts at (120, 0.9) in Python")
    log()

    # ---- 3. write cells.txt ----
    with open(CELLS, "w", encoding="utf-8", newline="\n") as f:
        for cid, off, L, model, kind, vals, tasks, runes in cells:
            f.write(f"cell {cid} {off} {L} {model} {ABORT_AT} {MARGIN} "
                    f"{kind if kind == 'tot' else 'v:' + ','.join(map(str, vals))}\n")
            f.write("R " + " ".join(map(str, runes)) + "\n")
            for t in tasks:
                f.write(f"T {t}\n")
    with open(EXPECTED, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(expected) + "\n")

    # ---- 4. build the Rust engine ----
    log("== build ==")
    env = dict(os.environ)
    env["CARGO_BUILD_JOBS"] = "8"
    r = subprocess.run(["cargo", "build", "--release"], cwd=HERE, env=env,
                       capture_output=True, text=True)
    if r.returncode != 0:
        log("  FAIL: cargo build --release failed:")
        log(r.stderr[-2000:])
        fails += 1
        write_out()
        return 1
    log("  ok: cargo build --release")
    log()

    exe = os.path.join(HERE, "target", "release", "h5rs.exe")

    # ---- 5. totient cross-check ----
    log("== totient cross-check (Rust internal vs h5slice.totient) ==")
    with open(os.path.join(HERE, "totient_rs.txt"), "wb") as f:
        subprocess.run([exe, "totient", "4000"], stdout=f, check=True)
    with open(os.path.join(HERE, "totient_rs.txt"), "r", encoding="utf-8") as f:
        rs = [int(x) for x in f.read().split()]
    if rs == tvals:
        log("  ok: totient(4000) identical")
    else:
        fails += 1
        log(f"  FAIL: totient mismatch (len {len(rs)} vs {len(tvals)})")
    log()

    # ---- 6. the parity runs ----
    expected_map = {}
    for line in expected:
        key = tuple(line.split()[:2])
        expected_map[key] = line

    log("== parity: engines scalar, fastscalar, fast ==")
    for engine in ("scalar", "fastscalar", "fast"):
        actual_path = os.path.join(HERE, f"actual_{engine}.txt")
        r = subprocess.run([exe, "parity", CELLS, actual_path, "--engine", engine],
                           cwd=HERE, capture_output=True, text=True)
        if r.returncode != 0:
            log(f"  FAIL: engine {engine} crashed: {r.stderr[-500:]}")
            fails += 1
            continue
        eng_checks = 0
        eng_fails = 0
        with open(actual_path, encoding="utf-8") as f:
            actual = [ln for ln in f.read().splitlines() if ln.strip()]
        if len(actual) != len(expected):
            log(f"  FAIL: engine {engine} wrote {len(actual)} lines, expected {len(expected)}")
            eng_fails += 1
        for aline in actual:
            parts = aline.split()
            key = (parts[0], parts[1])
            eline = expected_map.get(key)
            eng_checks += 1
            if eline is None:
                eng_fails += 1
                log(f"  FAIL [{engine}] unexpected line: {aline}")
                continue
            e = eline.split()
            ok = True
            if parts[2] != e[2]:  # ok vs abort
                ok = False
                log(f"  FAIL [{engine}] {key[0]} {key[1]}: abort mismatch "
                    f"rust={parts[2]} py={e[2]}")
            elif parts[2] == "ok" and key[1].startswith("init"):
                # ptrs=... score=... skips=...
                a_ptrs = parts[3][len("ptrs="):].split(",")
                e_ptrs = e[3][len("ptrs="):].split(",")
                a_score = float(parts[4][len("score="):])
                e_score = float(e[4][len("score="):])
                a_skips = int(parts[5][len("skips="):])
                e_skips = int(e[5][len("skips="):])
                if a_ptrs != e_ptrs:
                    ok = False
                    i = next((i for i in range(min(len(a_ptrs), len(e_ptrs)))
                              if a_ptrs[i] != e_ptrs[i]), -1)
                    log(f"  FAIL [{engine}] {key[0]} {key[1]}: ptr differ at {i} "
                        f"rust={a_ptrs[i] if i >= 0 else a_ptrs[:10]} "
                        f"py={e_ptrs[i] if i >= 0 else e_ptrs[:10]}")
                if a_skips != e_skips:
                    ok = False
                    log(f"  FAIL [{engine}] {key[0]} {key[1]}: skips {a_skips} vs {e_skips}")
                if abs(a_score - e_score) > 1e-9:
                    ok = False
                    log(f"  FAIL [{engine}] {key[0]} {key[1]}: score diff "
                        f"{a_score - e_score:.3e} (rust {a_score:.15f} py {e_score:.15f})")
            elif parts[2] == "ok" and key[1].startswith("dec"):
                a_ioc = float(parts[3][len("ioc="):])
                e_ioc = float(e[3][len("ioc="):])
                a_wcol = parts[4][len("wcol="):].split(",")
                e_wcol = e[4][len("wcol="):].split(",")
                a_skips = int(parts[5][len("skips="):])
                e_skips = int(e[5][len("skips="):])
                if abs(a_ioc - e_ioc) > 1e-12:
                    ok = False
                    log(f"  FAIL [{engine}] {key[0]} {key[1]}: ioc diff "
                        f"{a_ioc - e_ioc:.3e} (rust {a_ioc:.15f} py {e_ioc:.15f})")
                if a_wcol != e_wcol:
                    ok = False
                    log(f"  FAIL [{engine}] {key[0]} {key[1]}: wcol {a_wcol} vs {e_wcol}")
                if a_skips != e_skips:
                    ok = False
                    log(f"  FAIL [{engine}] {key[0]} {key[1]}: skips {a_skips} vs {e_skips}")
            if not ok:
                eng_fails += 1
        checks += eng_checks
        fails += eng_fails
        verdict = "PASS" if eng_fails == 0 else "FAIL"
        log(f"  engine {engine}: {eng_checks} checks, {eng_fails} fails -> {verdict}")
    log()

    # ---- 7. throughput ----
    log("== throughput (decode/s; campaign workhorse = aborting null cells) ==")
    bench = {}
    for threads in (1, 8):
        r = subprocess.run([exe, "bench", "--threads", str(threads), "--secs", "5",
                            "--engine", "fast"], cwd=HERE, capture_output=True, text=True)
        for ln in r.stdout.splitlines():
            if ln.startswith("null_abort_rate_dec_per_s"):
                bench[threads] = float(ln.split()[1])
            if ln.startswith("projection_hours_8_threads"):
                bench["proj"] = float(ln.split()[1])
        log(f"  bench {threads} thread(s): " + " | ".join(
            ln.strip() for ln in r.stdout.splitlines() if ln.strip()))
    r = subprocess.run([exe, "bench", "--threads", "1", "--secs", "3", "--engine", "fast",
                        "--full", os.path.join(HERE, "data", "truth.txt")],
                       cwd=HERE, capture_output=True, text=True)
    for ln in r.stdout.splitlines():
        if ln.startswith("full_decode_rate_dec_per_s"):
            bench["full"] = float(ln.split()[1])
    log(f"  full truth decode (init+EM, no abort): {bench.get('full', float('nan')):.0f} dec/s "
        f"single-threaded")
    if 1 in bench:
        log(f"  SUMMARY: single-thread {bench[1]:.0f} dec/s; 8-thread {bench.get(8, float('nan')):.0f} "
            f"dec/s; 880M-decodes projection {bench.get('proj', float('nan')):.1f} h at 8 threads")
    log()

    # ---- verdict ----
    verdict = "PASS" if fails == 0 else "FAIL"
    log(f"PARITY VERDICT: {verdict} ({checks} checks, {fails} fails) "
        f"in {time.time() - t_start:.0f}s")
    write_out()
    print(f"\nwrote {OUT}")
    return 0 if fails == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
