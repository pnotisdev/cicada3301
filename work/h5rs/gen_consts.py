"""Generate src/logf.rs: the bit-exact English prior constants the Rust engine embeds.

logf = H.english_logf() (Self-Reliance via work/sim.py, add-0.5 smoothed, np.log),
uni = float(np.sum(logf))/29, ln29 = math.log(29), ln028 = math.log(0.028).
Values are printed with repr() (round-trip exact f64). parity.py regenerates this file
and fails if the constants ever drift from what the Python decoder computes.
"""
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
WORK = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(WORK, "h5slice"))  # h5slice.py
sys.path.insert(0, WORK)  # work/ for sim.py

import h5slice as H

logf = H.english_logf()
uni = float(np := __import__("numpy").sum(logf)) / 29
ln29 = math.log(29)
ln028 = math.log(0.028)

vals = ",\n".join(f"    {v!r}" for v in logf.tolist())
src = f"""// Generated by gen_consts.py - DO NOT EDIT. Bit-exact Python values:
//   logf = H.english_logf()            (Self-Reliance via work/sim.py, add-0.5, np.log)
//   uni  = float(np.sum(logf)) / 29    (the unigram-null level)
//   ln29 = math.log(29); ln028 = math.log(0.028)
pub const LOGF: [f64; 29] = [
{vals},
];
pub const UNI: f64 = {uni!r};
pub const LN29: f64 = {ln29!r};
pub const LN028: f64 = {ln028!r};
"""
path = os.path.join(HERE, "src", "logf.rs")
os.makedirs(os.path.dirname(path), exist_ok=True)
with open(path, "w", encoding="utf-8", newline="\n") as f:
    f.write(src)
print(f"wrote {path}")
print("uni", repr(uni), "ln29", repr(ln29), "ln028", repr(ln028))
print("logf", [repr(v) for v in logf])
