"""Reference vectors for prngx, from real implementations (Python, numpy) and published values.

    python work/prngx/ref/gen_vectors.py > work/prngx/ref/vectors.txt

Line format: <gen> <seed> <map|raw|javaint> <values...>
  mt     numpy RandomState(seed) (init_genrand): raw = randint(0, 2**32, uint32); map 3 = randint(0, 29);
         map 5 = floor(random_sample() * 29)
  pymt   Python random.Random(seed) (init_by_array): raw = getrandbits(32); map 2 = randrange(29);
         map 5 = int(random() * 29)
  msvc   published MSVC rand() sequences (srand(1), srand(0))
  java   published java.util.Random values (seed 42, 0): nextInt()
  rand48 published srand48(1) lrand48() values
"""
import random

import numpy as np

SEEDS = [0, 1, 2, 42, 3301, 1033, 5489, 123456789, 2147483647, 4294967295]
N = 40


def main():
    print("# generated by gen_vectors.py; do not edit")
    for s in SEEDS:
        rs = np.random.RandomState(s)
        print("mt", s, "raw", *[int(x) for x in rs.randint(0, 2 ** 32, size=N, dtype=np.uint64)])
        rs = np.random.RandomState(s)
        print("mt", s, 3, *[int(x) for x in rs.randint(0, 29, size=N)])
        rs = np.random.RandomState(s)
        print("mt", s, 5, *[int(rs.random_sample() * 29) for _ in range(N)])
        r = random.Random(s)
        print("pymt", s, "raw", *[r.getrandbits(32) for _ in range(N)])
        r = random.Random(s)
        print("pymt", s, 2, *[r.randrange(29) for _ in range(N)])
        r = random.Random(s)
        print("pymt", s, 5, *[int(r.random() * 29) for _ in range(N)])
    # published values
    print("msvc", 1, "raw", 41, 18467, 6334, 26500, 19169, 15724, 11478, 29358, 26962, 24464)
    print("msvc", 0, "raw", 38, 7719, 21238, 2437, 8855, 11797, 8365, 32285, 10450, 30612)
    print("java", 42, "javaint", -1170105035, 234785527)
    print("java", 0, "javaint", -1155484576, -723955400)
    print("rand48", 1, 0, *[x % 29 for x in (89400484, 976015093)])


if __name__ == "__main__":
    main()
